(() => {
  const storageKey = "co5177-language";
  const controls = document.querySelector(".language-switch");
  function setLanguage(language) {
    const selected = language === "en" ? "en" : "vi";
    const dictionary = translations[selected];
    document.documentElement.lang = selected;
    document.querySelectorAll("[data-i18n]").forEach((element) => {
      const value = dictionary[element.dataset.i18n];
      if (value !== undefined) element.textContent = value;
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
      const value = dictionary[element.dataset.i18nAria];
      if (value !== undefined) element.setAttribute("aria-label", value);
    });
    document.querySelectorAll("[data-i18n-content]").forEach((element) => {
      const value = dictionary[element.dataset.i18nContent];
      if (value !== undefined) element.setAttribute("content", value);
    });
    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
      const value = dictionary[element.dataset.i18nAlt];
      if (value !== undefined) element.setAttribute("alt", value);
    });
    document.querySelectorAll("[data-language]").forEach((button) => {
      button.setAttribute("aria-pressed", String(button.dataset.language === selected));
    });
    try { localStorage.setItem(storageKey, selected); } catch { /* Switching still works without storage. */ }
  }
  let preferred = "vi";
  try { preferred = localStorage.getItem(storageKey) || "vi"; } catch { /* Vietnamese is the default. */ }
  setLanguage(preferred);
  if (controls) {
    controls.hidden = false;
    controls.addEventListener("click", (event) => {
      const button = event.target.closest("button[data-language]");
      if (button && controls.contains(button)) setLanguage(button.dataset.language);
    });
  }
})();
